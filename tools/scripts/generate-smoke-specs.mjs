#!/usr/bin/env node
/**
 * Generates `<entry>/<entry>.smoke.spec.ts` for every @ngxsmk/core secondary
 * entry point. The generated spec delegates to `tools/testing/smoke-harness.ts`,
 * which mounts every exported component standalone and asserts it renders
 * without errors — a floor of coverage that hand-written specs build on.
 *
 * Usage:
 *   node tools/scripts/generate-smoke-specs.mjs           # write/refresh
 *   node tools/scripts/generate-smoke-specs.mjs --check   # exit 1 if out of date
 */
import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const corePath = join(root, 'packages', 'core');
const harnessPath = join(root, 'tools', 'testing', 'smoke-harness.ts');
const check = process.argv.includes('--check');

/**
 * Entry points whose index re-exports a third-party package. Their components
 * are exercised by their own repositories, and mounting them here would only
 * test the upstream package's providers.
 */
const SKIP_ENTRY = new Set(['datepicker', 'tel-input']);

const SMOKE_SUFFIX = '.smoke.spec.ts';

function specSource(entry, dir) {
  const importPath = relative(dir, harnessPath).replace(/\\/g, '/').replace(/\.ts$/, '');
  return `// AUTO-GENERATED by tools/scripts/generate-smoke-specs.mjs - do not edit.
// Mounts every component exported from this entry point and asserts it renders
// without errors. Add behaviour tests in a separate \`${entry}.spec.ts\`.
import * as entry from './index';
import { smokeTestEntryPoint } from '${importPath}';

smokeTestEntryPoint('${entry}', entry as Record<string, unknown>);
`;
}

let written = 0;
let removed = 0;
let kept = 0;
const stale = [];

for (const entry of readdirSync(corePath).sort()) {
  const dir = join(corePath, entry);
  if (!statSync(dir).isDirectory()) continue;

  const smokePath = join(dir, `${entry}${SMOKE_SUFFIX}`);
  const wanted = existsSync(join(dir, 'index.ts')) && !SKIP_ENTRY.has(entry);
  const exists = existsSync(smokePath);

  if (!wanted) {
    if (exists) {
      if (check) stale.push(`${entry}: smoke spec should be removed`);
      else {
        unlinkSync(smokePath);
        removed++;
      }
    }
    continue;
  }

  const next = specSource(entry, dir);
  if (exists && readFileSync(smokePath, 'utf8') === next) {
    kept++;
    continue;
  }
  if (check) {
    stale.push(`${entry}: smoke spec ${exists ? 'out of date' : 'missing'}`);
    continue;
  }
  writeFileSync(smokePath, next);
  written++;
}

if (check) {
  if (stale.length) {
    console.error('Smoke specs out of date — run `npm run test:smoke:gen`:');
    for (const s of stale) console.error(`  ${s}`);
    process.exit(1);
  }
  console.log(`Smoke specs up to date (${kept} entry points).`);
} else {
  console.log(`Smoke specs: ${written} written, ${kept} unchanged, ${removed} removed.`);
}
